export const tutorialById = (id: string) => TUTORIALS.find(t => t.id === id);

/** The tutorial that answers a start error shown on 接待 (shared/reply-start-error.ts wording). */
export function tutorialForError(message: string): TutorialId {
  const m = message || '';
  if (/录屏|屏幕录制|允许咔哒看屏幕|辅助功能|隐私与安全性|MAC_/.test(m)) return 'mac-permissions';
  if (/试用次数|授权|卡密|激活/.test(m)) return 'licence';
  if (/皮卡|键鼠设备|USB|Pico|固件/i.test(m)) return 'hardware';
  if (/限流|429|调用太频繁|繁忙/.test(m)) return 'backup-and-pool';
  if (/模型|密钥|Key|视觉|基础地址|服务地址|Base URL|额度|余额|credential/i.test(m)) return 'model-setup';
  return 'chat-window';
}

const fold = (s: string) => s.toLowerCase().replace(/\s+/g, '');
/** Best tutorial for a free-text question (keyword hits, longer keywords count more); undefined when nothing matches. */
export function suggestTutorial(question: string): Tutorial | undefined {
  const q = fold(question);
  if (!q) return undefined;
  let best: Tutorial | undefined, score = 0;
  for (const t of TUTORIALS) {
    const s = [t.title, ...t.keywords].reduce((n, k) => fold(k) && q.includes(fold(k)) ? n + Math.min(4, fold(k).length) : n, 0);
    if (s > score) { best = t; score = s; }
  }
  return best;
}

/** The tutorials as handbook text for the 「问咔哒」 prompt; [id] marks the feature-index ids the answer may suggest. */
export function tutorialsHandbook(): string {
  return TUTORIALS.map(t => [
    `## 小教程：${t.title}（教程编号 ${t.id}）${t.links?.length ? ' ' + t.links.map(id => `[${id}]`).join(' ') : ''}`,
    ...t.steps.map((s, i) => `${i + 1}. ${s}`),
    ...(t.faq ?? []).map(f => `问：${f.q}　答：${f.a}`),
  ].join('\n')).join('\n\n');
}
