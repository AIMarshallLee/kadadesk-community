/** One plain sentence for a status / event / handoff reason. */
export function plainTalk(raw: string | undefined): string {
  const text = (raw ?? '').trim();
  if (!text) return '';
  // Model account / trial problems carry their own next step (who pays, where to paste a key); never the generic advice.
  const kind = modelFailureKind(text);
  if (kind) return MODEL_ADVICE[kind];
  for (const [pattern, plain] of rules) {
    const match = pattern.exec(text);
    if (match) return plain.replace('$1', match[1] ?? '');
  }
  return productMessage(text);
}

/** What the operator should do about a handed-over chat: nothing / look at the chat / fix settings. */
export function plainAction(raw: string | undefined): 'none' | 'look' | 'settings' {
  const plain = plainTalk(raw);
  if (/到「设置|在「设置」|服务人员|「开始」页/.test(plain)) return 'settings';
  if (/请看一眼|请你处理|需要你|交给你|转给你|等你审核/.test(plain)) return 'look';
  return 'none';
}
