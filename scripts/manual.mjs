// 使用手册 (docs/manual/*.md) → shared/manual-content.ts, plus the release guard.
//
//   node scripts/manual.mjs          regenerate shared/manual-content.ts from docs/manual (npm run manual; npm run build runs it)
//   node scripts/manual.mjs --check  fail unless the manual has a 更新记录 entry for package.json's version and the
//                                    generated module matches docs/manual (the packaging scripts call assertManualReady)
//
// The Markdown files are the source. The generated module is what the renderer and the local service import, so the
// manual ships inside the app bundle on every platform without extra files to copy.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MANUAL_DIR = 'docs/manual';
export const MANUAL_MODULE = 'shared/manual-content.ts';
export const CHANGELOG_FILE = '99-changelog.md';
const FILE_NAME = /^\d{2}-[a-z0-9-]+\.md$/;

/** @param {string} [root] */
export function readManualSources(root = process.cwd()) {
  const dir = join(root, MANUAL_DIR);
  return readdirSync(dir).filter(name => FILE_NAME.test(name)).sort().map(file => ({ file, markdown: readFileSync(join(dir, file), 'utf8').replace(/\r\n?/g, '\n') }));
}

/** @param {Array<{ file: string; markdown: string }>} sources */
export function renderManualModule(sources) {
  return `// Generated by scripts/manual.mjs from docs/manual/*.md — do not edit by hand; run \`npm run manual\`.\n`
    + `export const MANUAL_FILES: ReadonlyArray<{ file: string; markdown: string }> = ${JSON.stringify(sources, null, 2)};\n`;
}

/** Versions in the 更新记录, in file order (newest first): every `## 0.8.45` heading. @param {string} markdown */
export function changelogVersions(markdown) {
  return [...markdown.matchAll(/^##\s+v?(\d+\.\d+\.\d+)\s*$/gm)].map(m => m[1]);
}

/** The bullet text under one version's heading ('' when missing). @param {string} markdown @param {string} version */
export function changelogEntry(markdown, version) {
  const lines = markdown.split('\n');
  const start = lines.findIndex(line => new RegExp(`^##\\s+v?${version.replace(/\./g, '\\.')}\\s*$`).test(line));
  if (start < 0) return '';
  const rest = lines.slice(start + 1);
  const end = rest.findIndex(line => /^##?\s/.test(line));
  return (end < 0 ? rest : rest.slice(0, end)).join('\n').trim();
}

/** Everything a release needs from the manual. @param {string} [root] */
export function checkManual(root = process.cwd()) {
  const problems = [];
  const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
  const changelogPath = join(root, MANUAL_DIR, CHANGELOG_FILE);
  if (!existsSync(changelogPath)) problems.push(`缺少 ${MANUAL_DIR}/${CHANGELOG_FILE}（更新记录）`);
  else {
    const changelog = readFileSync(changelogPath, 'utf8').replace(/\r\n?/g, '\n');
    const versions = changelogVersions(changelog);
    if (!versions.includes(version)) problems.push(`更新记录里没有 ${version}：在 ${MANUAL_DIR}/${CHANGELOG_FILE} 最上面加「## ${version}」和这一版的改动`);
    else {
      if (versions[0] !== version) problems.push(`更新记录要最新的在最上面：${version} 应该排第一，现在第一个是 ${versions[0]}`);
      if (!/^\s*[-*]\s+\S/m.test(changelogEntry(changelog, version))) problems.push(`更新记录里 ${version} 下面还没有写改动（每条用「- 」开头）`);
    }
  }
  const modulePath = join(root, MANUAL_MODULE);
  const expected = renderManualModule(readManualSources(root)).replace(/\r\n/g, '\n');
  if (!existsSync(modulePath) || readFileSync(modulePath, 'utf8').replace(/\r\n/g, '\n') !== expected) problems.push(`${MANUAL_MODULE} 和 ${MANUAL_DIR} 不一致：运行 npm run manual`);
  return { version, problems };
}

/** Throws a plain message when the manual is not ready for this version; used before packaging. @param {string} [root] */
export function assertManualReady(root = process.cwd()) {
  const { version, problems } = checkManual(root);
  if (problems.length) throw new Error(`使用手册没有跟上 ${version}，已停止打包：\n- ${problems.join('\n- ')}\n每次发版同步更新使用手册（更新记录 + 涉及的章节），然后运行 npm run manual 再打包。`);
  return version;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = process.cwd();
  if (process.argv.includes('--check')) {
    try { console.log(`使用手册已包含 ${assertManualReady(root)} 的更新记录。`); }
    catch (error) { console.error(error instanceof Error ? error.message : error); process.exitCode = 1; }
  } else {
    const sources = readManualSources(root);
    const next = renderManualModule(sources);
    const target = join(root, MANUAL_MODULE);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== next) writeFileSync(target, next);
    console.log(`使用手册：${sources.length} 章 → ${MANUAL_MODULE}`);
  }
}
